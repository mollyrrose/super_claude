def _safe_ascii(s):
    return str(s).encode('ascii', errors='replace').decode('ascii')


def _read_config(config_path):
    try:
        with open(config_path, 'r', encoding='utf-8', errors='replace') as fh:
            return json.load(fh)
    except Exception:
        return {}


def _write_file(path, content):
    """Write content to path, creating parent dirs. Content must be str."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(content)


def _inject_config(template, config):
    """Embed JSON config into the plain HTML template's placeholder."""
    config_json = json.dumps(config, ensure_ascii=True, indent=2)
    return template.replace('"__DESIGN_CONFIG_JSON__"', config_json)


def main():
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument('--framework', default=None)
    parser.add_argument('--config', default=None)
    parser.add_argument('--out', default=None)

    try:
        args, _unknown = parser.parse_known_args()
    except Exception:
        print(json.dumps({"error": "bad arguments"}))
        return

    framework = (args.framework or '').lower().strip()
    config_path = args.config
    out_dir_arg = args.out

    if framework not in ('react', 'vue', 'plain'):
        print(json.dumps({"error": "framework must be react, vue, or plain"}))
        return

    if not config_path:
        print(json.dumps({"error": "--config path required"}))
        return

    config = _read_config(config_path)
    if not config:
        # Emit empty config as fallback
        config = {"version": 1, "theme": {"modes": ["light", "dark", "auto"], "default": "auto"},
                  "density": {"options": ["compact", "regular", "roomy"], "default": "regular"},
                  "accent": {"options": [], "default": ""},
                  "avatars": {"sets": [], "default": "", "enabled": False},
                  "effects": []}

    # Determine output directory
    if out_dir_arg:
        out_dir = os.path.abspath(out_dir_arg)
    else:
        out_dir = os.path.abspath(os.path.join('docs', 'design', 'proposals', 'design-tab'))

    written_files = []

    try:
        if framework == 'react':
            files = {
                'DesignSettings.tsx': _REACT_DESIGN_SETTINGS_TSX,
                'applyDesignConfig.ts': _REACT_APPLY_CONFIG_TS,
                'design-config.json': json.dumps(config, ensure_ascii=True, indent=2),
            }
            ext = 'tsx'
            apply_ext = 'ts'
        elif framework == 'vue':
            files = {
                'DesignSettings.vue': _VUE_DESIGN_SETTINGS_VUE,
                'applyDesignConfig.js': _VUE_APPLY_CONFIG_JS,
                'design-config.json': json.dumps(config, ensure_ascii=True, indent=2),
            }
            ext = 'vue'
            apply_ext = 'js'
        else:  # plain
            html_content = _inject_config(_PLAIN_DESIGN_SETTINGS_HTML, config)
            files = {
                'design-settings.html': html_content,
                'design-settings.js': _PLAIN_DESIGN_SETTINGS_JS,
                'design-config.json': json.dumps(config, ensure_ascii=True, indent=2),
            }
            ext = 'html'
            apply_ext = 'js'

        files_list_md = "\n".join("- " + f for f in sorted(files.keys()))
        wiring = _WIRING_MD_TEMPLATE.format(
            framework=framework,
            ext=ext,
            apply_ext=apply_ext,
            files_list=files_list_md,
        )
        files['WIRING.md'] = wiring

        for fname, content in files.items():
            out_path = os.path.join(out_dir, fname)
            # Safety: ensure we never write outside out_dir
            out_path_abs = os.path.abspath(out_path)
            out_dir_abs = os.path.abspath(out_dir)
            if not out_path_abs.startswith(out_dir_abs + os.sep) and out_path_abs != out_dir_abs:
                continue  # skip silently (should not happen with simple filenames)
            _write_file(out_path, content)
            written_files.append(fname)

    except Exception as exc:
        print(json.dumps({"error": "write failed: " + str(exc)}))
        return

    result = {
        "out": out_dir,
        "framework": framework,
        "files": sorted(written_files),
    }
    print(json.dumps(result, ensure_ascii=True))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print(json.dumps({"error": str(exc)}))
        sys.exit(0)
