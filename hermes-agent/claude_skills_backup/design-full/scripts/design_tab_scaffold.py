_REACT_APPLY_CONFIG_TS = '''\
// applyDesignConfig.ts -- PROPOSAL (see WIRING.md before integrating)
// Generated by design_tab_scaffold.py -- ASCII-only output.

export interface AppliedSettings {{
  theme: string;
  density: string;
  accent: string;
  avatarSet: string;
  effects: Record<string, boolean>;
}}

interface EffectDef {{
  id: string;
  reduced_motion_behavior: string;
}}

interface Config {{
  effects: EffectDef[];
}}

export function applyDesignConfig(settings: AppliedSettings, config: Config): void {{
  const root = document.documentElement;

  // Theme
  root.setAttribute("data-theme", settings.theme);

  // Auto: respect system preference
  if (settings.theme === "auto") {{
    const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
    root.setAttribute("data-theme", prefersDark ? "dark" : "light");
  }}

  // Density
  root.setAttribute("data-density", settings.density);

  // Accent color
  root.style.setProperty("--dg-accent", settings.accent);

  // Avatar set
  if (settings.avatarSet) {{
    root.setAttribute("data-avatar-set", settings.avatarSet);
  }}

  // Reduced-motion detection
  const prefersReducedMotion = window.matchMedia(
    "(prefers-reduced-motion: reduce)"
  ).matches;

  // Effects
  config.effects.forEach((effectDef) => {{
    const wanted = settings.effects[effectDef.id] ?? false;
    const allowed =
      !prefersReducedMotion ||
      effectDef.reduced_motion_behavior !== "disable";
    const active = wanted && allowed;
    root.setAttribute(
      `data-effect-${{effectDef.id}}`,
      active ? "on" : "off"
    );
  }});
}}
'''

